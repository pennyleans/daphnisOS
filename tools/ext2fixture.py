#!/usr/bin/env python3
"""tools/ext2fixture.py OUT.ci: the volume of the hosted ext2 tests (FS-4) as a cint module.

mke2fs makes an empty 256 KiB ext2 volume the way tools/mkdisk.sh makes the gate's: 4 KiB blocks, 128-byte inodes,
64 inodes, the features, UUID and hash seed named, no configuration file, the clock at 1; debugfs then sets the
three times of / and /lost+found to 1. The volume's 32,768 little-endian 64-bit words are written as runs of equal
nonzero words: run k is span(k) words of value(k) from word start(k) on. tests/fs/times_test.ci loads them into the hosted disk
(tests/hosted/src/blk.ci) and mounts it with src/ext2.ci as it is. KF-1: the module also carries the counts
dumpe2fs -h prints for the volume, and the free counts after debugfs writes a 5,000-byte file and makes a directory
there, for tests/fs/statfs_test.ci.

`--check OUT.ci` builds the module again and compares it with the committed one: exit 0 when equal."""
import os
import struct
import subprocess
import sys
import tempfile

BYTES = 256 * 1024


def volume():
    env = dict(os.environ, E2FSPROGS_FAKE_TIME="1", MKE2FS_CONFIG="/dev/null")
    with tempfile.TemporaryDirectory() as d:
        img = os.path.join(d, "v.img")
        subprocess.run(
            ["mke2fs", "-q", "-F", "-t", "ext2", "-b", "4096", "-I", "128", "-N", "64", "-m", "0",
             "-O", "none,dir_index,filetype,sparse_super", "-U", "6461706e-6869-7300-0000-000000000001",
             "-E", "hash_seed=6461706e-6869-7300-0000-000000000002,root_owner=0:0", "-L", "daphnis", img, "256K"],
            env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        script = "".join("sif %s %s 1\n" % (p, f) for p in ("/", "/lost+found") for f in ("atime", "ctime", "mtime"))
        subprocess.run(["debugfs", "-w", "-f", "-", img], input=script.encode(), env=env, check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        data = open(img, "rb").read()
        counts = dumpe2fs(img, env)
        # KF-1: the same volume after a 5,000-byte file `a` and a directory `d` are made in /, by debugfs
        five = os.path.join(d, "five")
        with open(five, "wb") as f:
            f.write(bytes((7 * i + 1) & 0xFF for i in range(5000)))   # no zero block: debugfs writes those as holes
        subprocess.run(["debugfs", "-w", "-f", "-", img], input=("write %s a\nmkdir d\n" % five).encode(), env=env,
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        after = dumpe2fs(img, env)
    assert len(data) == BYTES
    return struct.unpack("<%dQ" % (BYTES // 8), data), counts, after


def dumpe2fs(img, env):
    """The counts dumpe2fs -h prints: blocks, free blocks, reserved blocks, inodes, free inodes."""
    out = subprocess.run(["dumpe2fs", "-h", img], env=env, check=True, capture_output=True).stdout.decode()
    want = ["Block count", "Free blocks", "Reserved block count", "Inode count", "Free inodes"]
    got = {}
    for line in out.splitlines():
        k, _, v = line.partition(":")
        if k in want:
            got[k] = int(v)
    return [got[k] for k in want]


def module(volume_out):
    words, counts, after = volume_out
    runs = []
    for i, w in enumerate(words):
        if w == 0:
            continue
        if runs and runs[-1][2] == w and runs[-1][0] + runs[-1][1] == i:
            runs[-1][1] += 1
        else:
            runs.append([i, 1, w])
    n = len(runs)

    def rows(vals, fmt):
        out = []
        for k in range(0, n, 8):
            out.append("    " + ", ".join(fmt % v for v in vals[k:k + 8]))
        return ",\n".join(out)

    return (
        "// tests/fs/ext2_vol.ci: generated by tools/ext2fixture.py, not written by hand. An empty 256 KiB ext2 volume\n"
        "// (4 KiB blocks, 64 inodes, every time 1) as runs of equal nonzero 64-bit words.\n\n"
        "export const I64 SECTORS = %d;\n"
        "export const I64 RUNS = %d;\n\n"
        "// KF-1: what dumpe2fs -h prints for this volume, and its free counts after debugfs writes a 5,000-byte file\n"
        "// and makes a directory in /.\n"
        "export const I64 BLOCKS = %d;\n"
        "export const I64 FREE_BLOCKS = %d;\n"
        "export const I64 RESERVED_BLOCKS = %d;\n"
        "export const I64 INODES = %d;\n"
        "export const I64 FREE_INODES = %d;\n"
        "export const I64 FREE_BLOCKS_AFTER = %d;\n"
        "export const I64 FREE_INODES_AFTER = %d;\n\n"
        "I64[%d] START = [\n%s\n];\n\n"
        "I64[%d] SPAN = [\n%s\n];\n\n"
        "U64[%d] VALUE = [\n%s\n];\n\n"
        "// Run k: span(k) words of value(k) from word start(k) on.\n"
        "export I64 start(I64 k) { return START[k]; }\n"
        "export I64 span(I64 k) { return SPAN[k]; }\n"
        "export U64 value(I64 k) { return VALUE[k]; }\n"
        "// SPDX-License-Identifier: Apache-2.0\n"
    ) % (BYTES // 512, n, counts[0], counts[1], counts[2], counts[3], counts[4], after[1], after[4], n, rows([r[0] for r in runs], "%d"), n, rows([r[1] for r in runs], "%d"),
         n, rows([r[2] for r in runs], "0x%X"))


def main(argv):
    check = argv[:1] == ["--check"]
    paths = argv[1:] if check else argv
    if len(paths) != 1:
        sys.exit("usage: tools/ext2fixture.py [--check] OUT.ci")
    text = module(volume())
    if check:
        if open(paths[0]).read() != text:
            sys.exit("ext2fixture: %s is not what mke2fs and debugfs give here" % paths[0])
        print("ext2fixture: %s is the volume mke2fs and debugfs give" % paths[0])
        return
    with open(paths[0], "w") as f:
        f.write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
