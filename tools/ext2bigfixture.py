#!/usr/bin/env python3
"""tools/ext2bigfixture.py OUT.ci: the 512 MiB volume of tests/fs/ext2_big_test.ci (HW-15) as a cint module.

mke2fs makes the volume as tools/mkcintvol.sh makes the release stick's home (OUT 512M 32768): 4 KiB blocks, 128-byte
inodes, 32,768 inodes (8,192 a group in 4 groups), the features, UUID and hash seed named, no configuration file,
the clock at 1. debugfs sets the three times of / and /lost+found to 1, then marks inodes 12 to 32,760 in use and
sets each group's free inode count and the superblock's to what the bitmaps leave (0, 0, 0 and 8): the next inode
src/ext2.ci gives out is the 8,185th of the last group, the last byte of its bitmap. The volume's nonzero 64-bit
words are written as runs, as tools/ext2fixture.py writes its volume; the module also carries what dumpe2fs prints
for the volume and the blocks of group 3 a test reads on the device.

`--check OUT.ci` builds the module again and compares it with the committed one: exit 0 when equal."""
import os
import re
import struct
import subprocess
import sys
import tempfile

SIZE = "512M"
INODES = 32768
USED = 32760          # inodes 1 to USED in use


def run(cmd, env, data=None):
    return subprocess.run(cmd, input=data, env=env, check=True, capture_output=True).stdout.decode()


def volume():
    env = dict(os.environ, E2FSPROGS_FAKE_TIME="1", MKE2FS_CONFIG="/dev/null")
    env["PATH"] = env.get("PATH", "") + ":/usr/sbin:/sbin"
    with tempfile.TemporaryDirectory() as d:
        img = os.path.join(d, "v.img")
        run(["mke2fs", "-q", "-F", "-t", "ext2", "-b", "4096", "-I", "128", "-N", str(INODES), "-m", "0",
             "-O", "none,dir_index,filetype,sparse_super", "-U", "6461706e-6869-7300-0000-000000000003",
             "-E", "hash_seed=6461706e-6869-7300-0000-000000000004,root_owner=0:0", "-L", "daphnis-cint", img, SIZE],
            env)
        ipg = INODES // 4
        script = "".join("sif %s %s 1\n" % (p, f) for p in ("/", "/lost+found") for f in ("atime", "ctime", "mtime"))
        script += "seti <12> %d\n" % (USED - 11)
        for g in range(4):
            script += "set_bg %d free_inodes_count %d\n" % (g, max(0, min(ipg, (g + 1) * ipg - USED)))
        script += "ssv free_inodes_count %d\n" % (INODES - USED)
        run(["debugfs", "-w", "-f", "-", img], env, script.encode())
        dump = run(["dumpe2fs", img], env)
        with open(img, "rb") as f:
            data = f.read()
    return data, dump


def counts(dump):
    want = ["Block count", "Free blocks", "Inode count", "Free inodes", "Inodes per group", "Blocks per group"]
    got = {}
    for line in dump.splitlines():
        k, _, v = line.partition(":")
        if k in want and k not in got:
            got[k] = int(v)
    g3 = dump[dump.index("Group 3:"):]
    blocks = {
        "BLOCK_BITMAP_3": int(re.search(r"Block bitmap at (\d+)", g3).group(1)),
        "INODE_BITMAP_3": int(re.search(r"Inode bitmap at (\d+)", g3).group(1)),
        "INODE_TABLE_3": int(re.search(r"Inode table at (\d+)", g3).group(1)),
        "FIRST_FREE_3": int(re.search(r"Free blocks: (\d+)", g3).group(1)),
    }
    return [got[k] for k in want], blocks


def module(vol):
    data, dump = vol
    (blocks_n, free_b, inodes_n, free_i, ipg, bpg), g3 = counts(dump)
    assert inodes_n == INODES and ipg == INODES // 4 and free_i == INODES - USED
    words = struct.unpack("<%dQ" % (len(data) // 8), data)
    runs = []
    for i, w in enumerate(words):
        if w == 0:
            continue
        if runs and runs[-1][2] == w and runs[-1][0] + runs[-1][1] == i:
            runs[-1][1] += 1
        else:
            runs.append([i, 1, w])
    n = len(runs)

    def rows(vals, fmt):
        return ",\n".join("    " + ", ".join(fmt % v for v in vals[k:k + 8]) for k in range(0, n, 8))

    consts = "".join("export const I64 %s = %d;\n" % kv for kv in [
        ("SECTORS", len(data) // 512), ("RUNS", n), ("BLOCKS", blocks_n), ("FREE_BLOCKS", free_b),
        ("INODES", inodes_n), ("FREE_INODES", free_i), ("INODES_PER_GROUP", ipg), ("BLOCKS_PER_GROUP", bpg),
        ("USED", USED)] + sorted(g3.items()))
    return (
        "// tests/fs/ext2_big.ci: generated by tools/ext2bigfixture.py, not written by hand. The 512 MiB volume of\n"
        "// tools/mkcintvol.sh OUT 512M 32768 (4 KiB blocks, 32,768 inodes in 4 groups, every time 1) with inodes 1 to\n"
        "// USED in use, as runs of equal nonzero 64-bit words; the counts are dumpe2fs's, the blocks its group 3 lines.\n\n"
        + consts + "\n"
        "I64[%d] START = [\n%s\n];\n\n"
        "I64[%d] SPAN = [\n%s\n];\n\n"
        "U64[%d] VALUE = [\n%s\n];\n\n"
        "// Run k: span(k) words of value(k) from word start(k) on.\n"
        "export I64 start(I64 k) { return START[k]; }\n"
        "export I64 span(I64 k) { return SPAN[k]; }\n"
        "export U64 value(I64 k) { return VALUE[k]; }\n"
        "// SPDX-License-Identifier: Apache-2.0\n"
    ) % (n, rows([r[0] for r in runs], "%d"), n, rows([r[1] for r in runs], "%d"), n, rows([r[2] for r in runs], "0x%X"))


def main(argv):
    check = argv[:1] == ["--check"]
    paths = argv[1:] if check else argv
    if len(paths) != 1:
        sys.exit("usage: tools/ext2bigfixture.py [--check] OUT.ci")
    text = module(volume())
    if check:
        if open(paths[0]).read() != text:
            sys.exit("ext2bigfixture: %s is not what mke2fs and debugfs give here" % paths[0])
        print("ext2bigfixture: %s is the volume mke2fs and debugfs give" % paths[0])
        return
    with open(paths[0], "w") as f:
        f.write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
