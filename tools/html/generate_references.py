#!/usr/bin/env python3
"""Generate immutable CINT lookup bytes from the pinned WHATWG table."""
import argparse
import hashlib
import json
from pathlib import Path

PIN = 'd741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6'


def generate(root):
    data = (root / 'vendor/whatwg-html/entities.json').read_bytes()
    if hashlib.sha256(data).hexdigest() != PIN:
        raise ValueError('named reference data does not match its pin')
    entries = json.loads(data)
    names, rows = bytearray(), bytearray()
    for name, item in sorted(entries.items()):
        assert name.startswith('&') and 1 <= len(item['codepoints']) <= 2
        key = name[1:].encode('ascii')
        assert all(chr(c).isalnum() for c in key.rstrip(b';'))
        assert item['characters'] == ''.join(chr(c) for c in item['codepoints'])
        assert len(key) < 256 and len(names) < 65536
        rows.extend(len(names).to_bytes(2, 'little'))
        rows.append(len(key))
        for cp in item['codepoints'] + [0] * (2 - len(item['codepoints'])):
            assert 0 < cp <= 0x10ffff or cp == 0
            rows.extend(cp.to_bytes(3, 'little'))
        names.extend(key)

    def literal(data):
        return 'b"' + ''.join('\\x%02x' % b for b in data) + '"'

    result = '''// Generated by tools/html/generate_references.py. Do not edit.
// WHATWG HTML named references, BSD-3-Clause source incorporation.
// Attribution and pinned source bytes: vendor/whatwg-html/.
export const I64 SIZE = %d;
U8 row_byte(I64 at) { return %s[at]; }
U8 name_byte(I64 at) { return %s[at]; }
export I64 width(I64 index) {
    if (index < 0 || index >= SIZE) { return 0; }
    return row_byte(index * 9 + 2) as I64;
}
export U32 letter(I64 index, I64 depth) {
    if (index < 0 || index >= SIZE || depth < 0 || depth >= width(index)) { return 0; }
    I64 start = (row_byte(index * 9) as I64) + 256 * (row_byte(index * 9 + 1) as I64);
    return name_byte(start + depth) as U32;
}
export U32 point(I64 index, I64 which) {
    if (index < 0 || index >= SIZE || which < 0 || which > 1) { return 0; }
    I64 at = index * 9 + 3 + which * 3;
    return (row_byte(at) as U32) + 256 * (row_byte(at + 1) as U32) + 65536 * (row_byte(at + 2) as U32);
}
''' % (len(entries), literal(rows), literal(names))
    return result


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    root = Path(__file__).resolve().parents[2]
    dest = root / 'user/ci/web/reference_data.ci'
    result = generate(root)
    if args.check:
        assert dest.read_text() == result, 'generated named reference bytes differ'
    else:
        dest.write_text(result)


if __name__ == '__main__':
    main()
