#!/usr/bin/env python3
"""Generate packed immutable decoding indexes from pinned original WHATWG data."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / 'vendor/whatwg-encoding'


def packed_function(name, data):
    pages = [(at, data[at:at + 2048]) for at in range(0, len(data), 2048)]
    def tree(items, indent):
        if len(items) == 1:
            at, page = items[0]
            literal = ''.join('\\x%02x' % b for b in page)
            return [indent + f'return b"{literal}"[at - {at}] as I64;']
        mid = len(items) // 2
        return ([indent + f'if (at < {items[mid][0]}) {{'] + tree(items[:mid], indent + '    ')
                + [indent + '} else {'] + tree(items[mid:], indent + '    ') + [indent + '}'])
    return '\n'.join(['I64 ' + name + '(I64 at) {'] + tree(pages, '    ') + ['}'])


def normalized_wpt():
    manifest = json.loads((VENDOR / 'wpt-manifest.json').read_text())
    directory = ROOT / 'tests/html/corpus/encoding/wpt'
    for name, expected in manifest['sha256'].items():
        assert hashlib.sha256((directory / name).read_bytes()).hexdigest() == expected, name + ' WPT drift'
    fixtures = []
    for name in manifest['executed_static_decode_files']:
        source = (directory / name).read_text()
        matches = re.findall(r'(?m)^decode\(\s*\[([^\]]*)\],\s*("(?:[^"\\]|\\.)*")', source)
        for index, (raw, quoted) in enumerate(matches):
            data = [int(value.strip(), 0) for value in raw.split(',') if value.strip()]
            quoted = re.sub(r'\\x([0-9a-fA-F]{2})', r'\\u00\1', quoted)
            quoted = re.sub(r'\\u\{([0-9a-fA-F]+)\}', lambda m: chr(int(m[1], 16)), quoted)
            text = json.loads(quoted).encode('utf-16', 'surrogatepass').decode('utf-16')
            names = ['ISO-2022-JP'] if name.startswith('iso-') else ['GBK', 'gb18030'] if '/gb18030/' in name else ['GBK']
            fixtures.extend(dict(source=name, case=index, encoding=encoding, data=data,
                                 points=list(map(ord, text)), faults=text.count('\ufffd')) for encoding in names)
    return json.dumps(fixtures, indent=2, ensure_ascii=True) + '\n'


def generate():
    source = json.loads((VENDOR / 'SOURCE.json').read_text())
    for name, expected in source['sha256'].items():
        assert hashlib.sha256((VENDOR / name).read_bytes()).hexdigest() == expected, name + ' source drift'
    enc = [e for g in json.loads((VENDOR / 'encodings.json').read_bytes()) for e in g['encodings']]
    indexes = json.loads((VENDOR / 'indexes.json').read_bytes())
    aliases = sorted((alias, i + 1) for i, e in enumerate(enc) for alias in e['labels'])
    alias_data = bytearray(); alias_offsets = []
    for alias, ident in aliases:
        alias_offsets.append(len(alias_data)); alias_data.extend(alias.encode() + b'\0' + bytes([ident]))
    text = ['// Generated by tools/html/generate_encodings.py from pinned WHATWG sources.',
            'export const I64 COUNT = ' + str(len(enc)) + ';', packed_function('alias_byte', alias_data)]
    text.append('export I64 alias_count() { return ' + str(len(aliases)) + '; }')
    offs = b''.join(int(x).to_bytes(2, 'little') for x in alias_offsets)
    text.append(packed_function('alias_offset_byte', offs))
    text.append('export I64 alias_offset(I64 index) { return alias_offset_byte(index * 2) + 256 * alias_offset_byte(index * 2 + 1); }')
    text.append('export I64 alias_character(I64 at) { return alias_byte(at); }')
    table_names = sorted(indexes)
    raw = bytearray(); offsets = {}; lengths = {}
    for name in table_names:
        if name == 'gb18030-ranges': continue
        offsets[name] = len(raw); lengths[name] = len(indexes[name])
        for cp in indexes[name]: raw.extend((0xffffff if cp is None else cp).to_bytes(3, 'little'))
    text.append(packed_function('table_byte', raw))
    text.append('''export I64 point(I64 table, I64 pointer) {
    I64 at = -1;''')
    for i, name in enumerate(table_names):
        if name == 'gb18030-ranges': continue
        text.append(f'    if (table == {i} && pointer >= 0 && pointer < {lengths[name]}) {{ at = {offsets[name]} + pointer * 3; }}')
    text.append('''    if (at < 0) { return -1; }
    I64 cp = table_byte(at) + 256 * table_byte(at + 1) + 65536 * table_byte(at + 2);
    if (cp == 16777215) { return -1; }
    return cp;
}''')
    text.append('export I64 single(I64 encoding, I64 pointer) {')
    for i, e in enumerate(enc[1:29], 2):
        name = 'iso-8859-8' if i == 10 else e['name'].lower()
        text.append(f'    if (encoding == {i}) {{ return point({table_names.index(name)}, pointer); }}')
    text.append('''    return -1;
}''')
    for name in ['gb18030','big5','jis0208','jis0212','euc-kr']:
        text.append(f'export I64 {name.replace("-", "_")}(I64 pointer) {{ return point({table_names.index(name)}, pointer); }}')
    ranges = indexes['gb18030-ranges']
    raw_ranges = b''.join(int(v).to_bytes(3,'little') for row in ranges for v in row)
    text.append(packed_function('range_byte', raw_ranges))
    text.append('I64 range_value(I64 index, I64 column) { I64 at = index * 6 + column * 3; return range_byte(at) + 256 * range_byte(at + 1) + 65536 * range_byte(at + 2); }')
    text.append('''export I64 gb_range(I64 pointer) {
    if ((pointer > 39419 && pointer < 189000) || pointer > 1237575) { return -1; }
    if (pointer == 7457) { return 59335; }
    I64 low = 0; I64 high = ''' + str(len(ranges)) + ''';
    while (low < high) { I64 mid = low + (high - low) / 2; if (range_value(mid, 0) <= pointer) { low = mid + 1; } else { high = mid; } }
    return range_value(low - 1, 1) + pointer - range_value(low - 1, 0);
}''')
    metadata = {'encoding_pin': source['commit'], 'encodings': [dict(id=i + 1, **e) for i, e in enumerate(enc)],
                'tables': {name: {'entries': len(values), 'mapped': sum(v is not None for v in values)} for name, values in indexes.items()},
                'alias_count': len(aliases), 'packed_table_bytes': len(raw)}
    return '\n'.join(text) + '\n', json.dumps(metadata, indent=2) + '\n'


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--check', action='store_true'); args = ap.parse_args()
    text, metadata = generate()
    for path, content in [(ROOT / 'user/ci/web/encoding_data.ci', text), (VENDOR / 'generated-metadata.json', metadata), (ROOT / 'tests/html/corpus/encoding/wpt-cases.json', normalized_wpt())]:
        if args.check: assert path.read_text() == content, str(path) + ' generated drift'
        else: path.write_text(content)
    print('40 encodings; ' + str(json.loads(metadata)['alias_count']) + ' aliases; pinned data, WPT and generated tables verified')


if __name__ == '__main__': main()
