"""Regenerate Unicode integer tables using only the exact pinned Vim, without Python's Unicode version."""
import json
from pathlib import Path
import subprocess
import tempfile
import vim_leg
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
def main():
    assert vim_leg.version() == (HERE/'VIM_VERSION').read_text().strip(), 'Vim pin differs'
    with tempfile.TemporaryDirectory() as tmp:
        dest = Path(tmp)/'unicode.json'
        source = (HERE/'unicode.vim').read_text().replace('/tmp/cvim-unicode.json', str(dest))
        script = Path(tmp)/'tables.vim'; script.write_text(source)
        subprocess.run(['vim','-Nu','NONE','-n','-N','-es','-S',str(script)], check=True)
        data = json.loads(dest.read_text())
    ranges=[]
    by_delta={}
    for cp,to in data['toggle']: by_delta.setdefault(to-cp,[]).append(cp)
    for delta,points in by_delta.items():
        i=0
        while i<len(points):
            step=points[i+1]-points[i] if i+1<len(points) else 1
            if step>2: step=1
            j=i+1
            while j<len(points) and points[j]-points[j-1]==step: j+=1
            ranges.append((points[i],points[j-1],step,delta)); i=j
    lines=['// Generated by tests/cvim/unicode.py from the exact pinned Vim.',
           '// Integer lookup only; no host locale or character library at runtime.',
           'export I64 class_of(I64 cp) {']
    for lo,hi,cl in data['classes']:
        if cl!=2: lines.append(f'    if (cp >= {lo} && cp <= {hi}) {{ return {cl}; }}')
    lines+=['    return 2;', '}', 'export I64 toggle_case(I64 cp) {']
    for lo,hi,step,delta in sorted(ranges):
        guard=f' && (cp - {lo}) % 2 == 0' if step==2 else ''
        lines.append(f'    if (cp >= {lo} && cp <= {hi}{guard}) {{ return cp {"+" if delta>=0 else "-"} {abs(delta)}; }}')
    lines+=['    return cp;', '}', '// SPDX-License-Identifier: Apache-2.0']
    (ROOT/'user/ci/cvim/unicode.ci').write_text('\n'.join(lines)+'\n')
if __name__=='__main__': main()
